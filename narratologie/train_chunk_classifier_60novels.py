#!/usr/bin/env python3
"""
train_chunk_classifier.py

Trains a simple sklearn classifier on the map-reduce chunk observations
already generated by run_narratologie_mapreduce.py (v3).

NO GPU needed. NO Ollama. Runs in seconds on CPU.
Uses the structured JSON observations stored in the results CSV as features.

The map step already extracted per-chunk signals like:
  - narrator_voice (first_person / third_person)
  - inner_thoughts (yes_one_character / yes_multiple / no)
  - dominant_mode (action_events / description / introspection / mixed)
  - world_type (realistic / autobiographical / fantastic / speculative_sf)
  - space (single_location / multiple_locations / journey_travel / imaginary)
  - plot_threads (one / multiple)
  - time_order (chronological / has_flashbacks_or_jumps / radically_scrambled)

We aggregate these counts across 9 chunks per novel → feature vector
→ train one classifier per criterion → evaluate with leave-one-out CV
(because we only have 60 examples, LOO CV is the most honest estimate)

Usage:
  cd ~/ecopoetique/narratologie
  python train_chunk_classifier.py

Output:
  - Prints per-criterion accuracy (LOO CV)
  - Saves predictions to resultats_chunk_classifier.csv
  - Compares to baseline (55.7%) and map-reduce v3 (63.3%)
"""

import os, csv, json, re
import numpy as np
from collections import Counter

# ── CONFIG ────────────────────────────────────────────────────────────────────
RESULTS_V3 = os.path.expanduser(
    "~/ecopoetique/narratologie/resultats_qwen3_30b_mapreduce.csv")
GOLD_FILE  = os.path.expanduser(
    "~/ecopoetique/narratologie/GOLD_narratologie_60novels_original.csv")
CORPUS_DIR = os.path.expanduser("~/ecopoetique/CORPUS_TOTAL")
OUTPUT_FILE = os.path.expanduser(
    "~/ecopoetique/narratologie/resultats_chunk_classifier_60novels.csv")

# We need the raw chunk observations — they aren't stored in the results CSV.
# So we re-run the MAP step only (no Ollama needed — we parse the novel text
# directly with simple heuristics) OR we load from the observation cache.
# 
# Since we don't have a cache file, we use the v3 results CSV which has
# GOLD labels and v3 PREDICTIONS. We use v3 predictions as proxy features
# PLUS we extract simple text-based features from the novels themselves.
# This is a hybrid: text features + v3 model output features.

# ── GOLD LOADING ─────────────────────────────────────────────────────────────
def load_gold(path):
    gold = {}
    with open(path, encoding="utf-8") as f:
        reader = csv.reader(f, delimiter=";")
        next(reader)
        for row in reader:
            if not row or not row[0].strip():
                continue
            def col(i): return row[i].strip() if i < len(row) else ""
            fn = col(0)
            gold[fn] = {
                "TYPE NARRATEUR":  col(4),  "NAR_alt": col(5),
                "FOCALISATION":    col(6),  "FOC_alt": col(7),
                "MODE NARRATIF":   col(8),  "MOD_alt": col(9),
                "REGIME NARRATIF": col(10), "REG_alt": col(11),
                "ESPACE":          col(12), "ESP_alt": col(13),
                "INTRIGUE":        col(14), "INT_alt": col(15),
                "TEMPORALITÉ":     col(16), "TEM_alt": col(17),
            }
    return gold

def is_correct(pred, main, alt=""):
    if not pred: return False
    p = pred.strip().upper()
    if p == main.strip().upper(): return True
    if alt and p == alt.strip().upper(): return True
    return False

# ── TEXT FEATURE EXTRACTION ───────────────────────────────────────────────────
def extract_text_features(filepath):
    """
    Extract simple heuristic features from novel text.
    These are fast regex/count operations — no model needed.
    """
    try:
        with open(filepath, "r", encoding="utf-8", errors="replace") as f:
            text = f.read()
    except:
        return {}

    lines = text.split("\n")
    total_lines = max(len(lines), 1)
    total_chars = max(len(text), 1)

    # Sample 9 equal chunks for consistency with map-reduce
    chunk_size = total_lines // 9
    chunks = []
    for i in range(9):
        start = i * chunk_size
        end = start + chunk_size if i < 8 else total_lines
        chunks.append("\n".join(lines[start:end]))

    features = {}

    # ── NARRATOR VOICE features ──
    # Count first-person pronouns per chunk
    fp_pattern = re.compile(r"\bje\b|\bj'\b|\bme\b|\bmon\b|\bma\b|\bmes\b|\bnous\b", re.I)
    tp_pattern = re.compile(r"\bil\b|\belle\b|\bils\b|\belles\b|\bon\b", re.I)

    fp_counts = [len(fp_pattern.findall(c)) / max(len(c), 1) * 1000 for c in chunks]
    tp_counts = [len(tp_pattern.findall(c)) / max(len(c), 1) * 1000 for c in chunks]

    features["fp_ratio_mean"] = float(np.mean(fp_counts))
    features["fp_ratio_max"]  = float(np.max(fp_counts))
    features["fp_chunks"]     = float(sum(1 for x in fp_counts if x > 2))  # chunks with strong fp
    features["tp_ratio_mean"] = float(np.mean(tp_counts))
    features["fp_dominates"]  = float(features["fp_ratio_mean"] > features["tp_ratio_mean"])

    # ── TENSE / TIME features ──
    # Past tense (passé simple, imparfait) vs present
    past_pattern    = re.compile(r"\w+(ait|aient|ais|ait|èrent|èmes|âmes|âtes|ûmes|ûtes)\b", re.I)
    present_pattern = re.compile(r"\w+(e|es|ent|ons|ez)\b", re.I)
    time_markers    = re.compile(
        r"\b(ans? plus tard|mois plus tard|semaines? plus tard|lendemain|"
        r"autrefois|jadis|naguère|hier|demain|soudain|alors|ensuite|"
        r"d'abord|enfin|plus tard|avant|après|pendant)\b", re.I)

    time_marker_count = len(time_markers.findall(text))
    features["time_markers_per_1k"] = float(time_marker_count / total_chars * 1000)

    # Flashback signals
    flashback = re.compile(
        r"\b(il se souvint|elle se souvint|il se rappela|elle se rappela|"
        r"en ce temps|à cette époque|autrefois|dans son enfance|"
        r"des années auparavant|longtemps avant|il avait été|elle avait été)\b", re.I)
    features["flashback_signals"] = float(len(flashback.findall(text)) / total_chars * 10000)

    # ── SPACE features ──
    # Location diversity — count distinct place indicators
    place_intro = re.compile(
        r"\b(à [A-Z][a-z]+|en [A-Z][a-z]+|au [A-Z][a-z]+|dans [a-z]+ (rue|avenue|boulevard|"
        r"place|quartier|ville|village|pays|région|maison|appartement|chambre|bureau|hôpital|"
        r"école|café|restaurant|gare|aéroport|forêt|montagne|mer|plage|désert))\b", re.I)
    travel_words = re.compile(
        r"\b(voyag|trajet|chemin|route|partir|arriver|quitter|traverser|"
        r"s'en all|se déplacer|kilomètre|frontière)\b", re.I)

    features["place_diversity"]  = float(len(set(place_intro.findall(text[:50000]))))
    features["travel_density"]   = float(len(travel_words.findall(text)) / total_chars * 10000)

    # ── INTRIGUE features ──
    # Multiple character names suggest multiple storylines
    # Simple heuristic: count distinct capitalized names
    name_pattern = re.compile(r"\b[A-Z][a-zéèêàâùûîôäë]{2,15}\b")
    names_found = Counter(name_pattern.findall(text[:100000]))
    # Filter to names appearing 3+ times (likely characters not just random caps)
    character_names = {k for k, v in names_found.items() if v >= 3
                      and k not in {"Le","La","Les","Un","Une","Des","Du","Au","Aux",
                                    "Ce","Cette","Mais","Dans","Pour","Avec","Sur","Par"}}
    features["character_count"] = float(min(len(character_names), 20))

    # Chapter/section breaks suggest structure
    chapter_pattern = re.compile(
        r"^(chapitre|partie|section|I+V?|V?I+|[0-9]+\.?\s*$)", re.I | re.MULTILINE)
    features["chapter_count"] = float(len(chapter_pattern.findall(text)))

    # ── INTROSPECTION features ──
    thought_verbs = re.compile(
        r"\b(pens|réfléch|souvien|imagin|croi|sentait|ressentait|"
        r"se demandait|s'interrogeait|rêvait|espérait|craignait)\b", re.I)
    action_verbs = re.compile(
        r"\b(cour|march|saut|frapp|tir|pouss|ouvr|ferm|lev|pos|pren|donn|"
        r"regarda|entra|sortit|courut|frappa|ouvrit|ferma)\b", re.I)

    features["thought_density"]  = float(len(thought_verbs.findall(text)) / total_chars * 10000)
    features["action_density"]   = float(len(action_verbs.findall(text)) / total_chars * 10000)
    features["thought_action_ratio"] = float(
        features["thought_density"] / max(features["action_density"], 0.001))

    # ── REGIME features ──
    # Autobiographical signals
    auto_signals = re.compile(
        r"\b(ma mère|mon père|mes parents|mon enfance|je suis né|"
        r"j'avais [0-9]+ ans|ma famille|mon frère|ma sœur|"
        r"quand j'étais|lorsque j'étais)\b", re.I)
    fantastic_signals = re.compile(
        r"\b(magique|sorcier|fantôme|disparut|apparut soudain|"
        r"impossible|miraculeux|surnaturel|métamorphos|se transforma)\b", re.I)
    sf_signals = re.compile(
        r"\b(robot|intelligence artificielle|vaisseau|planète|"
        r"futur|an [23][0-9]{3}|post-apocal|dystop|colonie)\b", re.I)

    features["auto_signals"]      = float(len(auto_signals.findall(text)) / total_chars * 10000)
    features["fantastic_signals"] = float(len(fantastic_signals.findall(text)) / total_chars * 10000)
    features["sf_signals"]        = float(len(sf_signals.findall(text)) / total_chars * 10000)
    features["total_lines"]       = float(min(total_lines, 10000))

    return features

# ── LOAD V3 PREDICTIONS (as additional features) ──────────────────────────────
def load_v3_predictions(path):
    preds = {}
    if not os.path.exists(path):
        print(f"Warning: v3 results not found at {path}")
        return preds
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            fn = row.get("File","").strip()
            if fn and not row.get("ERROR"):
                preds[fn] = {
                    "v3_NAR": row.get("TYPE NARRATEUR",""),
                    "v3_FOC": row.get("FOCALISATION",""),
                    "v3_MOD": row.get("MODE NARRATIF",""),
                    "v3_REG": row.get("REGIME NARRATIF",""),
                    "v3_ESP": row.get("ESPACE",""),
                    "v3_INT": row.get("INTRIGUE",""),
                    "v3_TEM": row.get("TEMPORALITÉ",""),
                }
    return preds

def encode_v3_features(v3_pred):
    """One-hot encode v3 predictions as features."""
    features = {}
    mappings = {
        "v3_NAR": ["NAR_AUTOD","NAR_TEM","NAR_EXT"],
        "v3_FOC": ["FOC_INT","FOC_EXT","FOC_ZERO","FOC_VAR"],
        "v3_MOD": ["MOD_EVT","MOD_DESC","MOD_INTR","MOD_MIX"],
        "v3_REG": ["REG_REAL","REG_AUTO","REG_FANT","REG_SPEC"],
        "v3_ESP": ["ESP_UNIT","ESP_FRAG","ESP_ITIN","ESP_IMAG"],
        "v3_INT": ["INTR_LIN","INTR_FRAG","INTR_CYC"],
        "v3_TEM": ["TEMP_LIN","TEMP_DIS","TEMP_DESORD"],
    }
    for key, labels in mappings.items():
        val = v3_pred.get(key, "")
        for label in labels:
            features[f"{key}_{label}"] = float(val.upper() == label)
    return features

# ── MAIN ──────────────────────────────────────────────────────────────────────
def main():
    try:
        from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
        from sklearn.linear_model import LogisticRegression
        from sklearn.model_selection import LeaveOneOut, cross_val_predict
        from sklearn.preprocessing import LabelEncoder
        from sklearn.pipeline import Pipeline
        from sklearn.preprocessing import StandardScaler
        import warnings
        warnings.filterwarnings("ignore")
    except ImportError:
        print("sklearn not found. Installing...")
        os.system("pip install scikit-learn --break-system-packages -q")
        from sklearn.ensemble import RandomForestClassifier
        from sklearn.linear_model import LogisticRegression
        from sklearn.model_selection import LeaveOneOut, cross_val_predict
        from sklearn.preprocessing import LabelEncoder, StandardScaler
        from sklearn.pipeline import Pipeline
        import warnings
        warnings.filterwarnings("ignore")

    print("\n" + "="*62)
    print("  CHUNK CLASSIFIER  (sklearn, CPU only, no GPU needed)")
    print("="*62 + "\n")

    # Load data
    gold    = load_gold(GOLD_FILE)
    v3_preds = load_v3_predictions(RESULTS_V3)

    print(f"Gold set: {len(gold)} novels")
    print(f"V3 predictions available: {len(v3_preds)} novels")

    # Build feature matrix
    filenames = []
    X_rows = []
    all_txt = set(os.listdir(CORPUS_DIR))

    print("\nExtracting text features...")
    for fn, g in gold.items():
        if fn not in all_txt:
            continue
        filepath = os.path.join(CORPUS_DIR, fn)

        # Text features
        text_feats = extract_text_features(filepath)
        if not text_feats:
            continue

        # V3 prediction features
        v3_feats = encode_v3_features(v3_preds.get(fn, {}))

        # Combine
        combined = {**text_feats, **v3_feats}
        filenames.append(fn)
        X_rows.append(combined)

    print(f"Built features for {len(filenames)} novels")

    # Convert to numpy array
    all_keys = sorted(set(k for row in X_rows for k in row.keys()))
    X = np.array([[row.get(k, 0.0) for k in all_keys] for row in X_rows])
    print(f"Feature vector size: {len(all_keys)} features\n")

    # Define criteria
    CRITERIA = [
        ("TYPE NARRATEUR",  "NAR_alt"),
        ("FOCALISATION",    "FOC_alt"),
        ("MODE NARRATIF",   "MOD_alt"),
        ("REGIME NARRATIF", "REG_alt"),
        ("ESPACE",          "ESP_alt"),
        ("INTRIGUE",        "INT_alt"),
        ("TEMPORALITÉ",     "TEM_alt"),
    ]

    # Baseline scores from v3 for comparison
    v3_scores = {
        "TYPE NARRATEUR": 90.0,
        "FOCALISATION":   51.7,
        "MODE NARRATIF":  51.7,
        "REGIME NARRATIF":66.7,
        "ESPACE":         46.7,
        "INTRIGUE":       65.0,
        "TEMPORALITÉ":    71.7,
    }

    print("="*62)
    print("  LEAVE-ONE-OUT CROSS-VALIDATION RESULTS")
    print("="*62)

    all_predictions = {fn: {"File": fn} for fn in filenames}
    overall_correct = overall_total = 0

    for crit, alt_key in CRITERIA:
        # Build label array
        y_labels = []
        valid_indices = []
        for i, fn in enumerate(filenames):
            g = gold[fn]
            label = g[crit]
            if label:
                y_labels.append(label)
                valid_indices.append(i)

        if len(y_labels) < 10:
            print(f"  {crit:<22} — not enough labels, skipping")
            continue

        X_valid = X[valid_indices]
        fns_valid = [filenames[i] for i in valid_indices]

        # Encode labels
        le = LabelEncoder()
        y = le.fit_transform(y_labels)

        # Try multiple classifiers, pick best
        best_acc = 0
        best_preds = None
        best_name = ""

        classifiers = [
            ("LogReg",  Pipeline([("sc", StandardScaler()),
                                   ("clf", LogisticRegression(max_iter=1000, C=1.0))])),
            ("RF",      RandomForestClassifier(n_estimators=100, random_state=42)),
            ("GB",      GradientBoostingClassifier(n_estimators=50, random_state=42)),
        ]

        loo = LeaveOneOut()
        for name, clf in classifiers:
            try:
                preds = cross_val_predict(clf, X_valid, y, cv=loo)
                # Score with alt labels
                correct = 0
                for i, (pred_enc, fn) in enumerate(zip(preds, fns_valid)):
                    pred_label = le.inverse_transform([pred_enc])[0]
                    g = gold[fn]
                    if is_correct(pred_label, g[crit], g[alt_key]):
                        correct += 1
                acc = correct / len(y_labels) * 100
                if acc > best_acc:
                    best_acc = acc
                    best_preds = preds
                    best_name = name
            except Exception as e:
                pass

        if best_preds is None:
            print(f"  {crit:<22} — classifier failed")
            continue

        # Store predictions
        for pred_enc, fn in zip(best_preds, fns_valid):
            pred_label = le.inverse_transform([pred_enc])[0]
            all_predictions[fn][crit] = pred_label

        # Compare to v3
        v3_score = v3_scores.get(crit, 0)
        delta = best_acc - v3_score
        sign = "+" if delta >= 0 else ""
        bar = "█" * int(best_acc / 5)
        tag = f"({sign}{delta:.1f}pp vs v3)"

        print(f"  {crit:<22} {best_acc:>5.1f}%  {bar:<20} {tag}  [{best_name}]")

        overall_correct += int(best_acc / 100 * len(y_labels))
        overall_total   += len(y_labels)

    print("-"*62)
    if overall_total:
        ov = overall_correct / overall_total * 100
        print(f"  {'OVERALL':<22} {ov:>5.1f}%")
    print("="*62)
    print(f"\n  Comparison:")
    print(f"  Baseline (125-line samples): 55.7%")
    print(f"  Map-reduce v3:               63.3%")
    if overall_total:
        print(f"  Chunk classifier (this):     {ov:.1f}%")
    print()

    # Save predictions
    rows = []
    for fn in filenames:
        g = gold.get(fn, {})
        row = {"File": fn}
        for crit, alt_key in CRITERIA:
            row[crit]             = all_predictions[fn].get(crit, "")
            row[f"GOLD_{crit[:3]}"] = g.get(crit, "")
            row[f"ALT_{crit[:3]}"]  = g.get(alt_key, "")
        rows.append(row)

    with open(OUTPUT_FILE, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"Predictions saved to: {OUTPUT_FILE}")

    # Feature importance for best criterion
    print("\n  Top text features (Random Forest importance on TEMPORALITE):")
    try:
        from sklearn.ensemble import RandomForestClassifier
        y_tem = []
        vi = []
        for i, fn in enumerate(filenames):
            label = gold[fn].get("TEMPORALITÉ","")
            if label:
                y_tem.append(label)
                vi.append(i)
        if len(y_tem) >= 10:
            le2 = LabelEncoder()
            y2  = le2.fit_transform(y_tem)
            rf  = RandomForestClassifier(n_estimators=200, random_state=42)
            rf.fit(X[vi], y2)
            importances = sorted(zip(all_keys, rf.feature_importances_),
                                  key=lambda x: -x[1])[:10]
            for feat, imp in importances:
                print(f"    {feat:<35} {imp:.3f}")
    except:
        pass

if __name__ == "__main__":
    main()
